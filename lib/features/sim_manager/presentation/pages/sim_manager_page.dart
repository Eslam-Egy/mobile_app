import 'package:material_ui/material_ui.dart';
import 'package:mobile_scanner/mobile_scanner.dart';
import '../../data/models/test_sim_model.dart';
import '../../domain/entities/test_sim_entity.dart';
import '../manager/sim_manager_notifier.dart';
import '../widgets/sim_card_item_widget.dart';
import '../widgets/sim_qr_dialog_widget.dart';
import '../widgets/add_sim_dialog_widget.dart';

class SimManagerPage extends StatefulWidget {
  final SimManagerNotifier notifier;
  final Function(String imsi, String extension) onStartFieldTest;

  const SimManagerPage({
    super.key,
    required this.notifier,
    required this.onStartFieldTest,
  });

  @override
  State<SimManagerPage> createState() => _SimManagerPageState();
}

class _SimManagerPageState extends State<SimManagerPage> {
  @override
  void initState() {
    super.initState();
    widget.notifier.loadSimCards();
  }

  void _showAddDialog() {
    showDialog(
      context: context,
      builder: (_) => AddSimDialogWidget(
        onSave: (sim) => widget.notifier.addSimCard(sim),
      ),
    );
  }

  void _showQrDialog(TestSimEntity sim) {
    showDialog(
      context: context,
      builder: (_) => SimQrDialogWidget(
        sim: sim,
        onStartFieldTest: () => widget.onStartFieldTest(sim.imsi, sim.extension),
      ),
    );
  }

  void _openQrScanner() {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (ctx) {
        return Container(
          height: MediaQuery.of(context).size.height * 0.75,
          decoration: const BoxDecoration(
            color: Color(0xFF1E222B),
            borderRadius: BorderRadius.vertical(top: Radius.circular(20)),
          ),
          child: Column(
            children: [
              AppBar(
                title: const Text('Scan Lab Test SIM QR', style: TextStyle(color: Colors.white, fontSize: 16)),
                backgroundColor: Colors.transparent,
                elevation: 0,
                leading: IconButton(
                  icon: const Icon(Icons.close, color: Colors.white),
                  onPressed: () => Navigator.of(ctx).pop(),
                ),
              ),
              const Padding(
                padding: EdgeInsets.symmetric(horizontal: 16.0),
                child: Text(
                  'Point camera at a Test SIM QR code generated by this companion app.',
                  style: TextStyle(color: Colors.white70, fontSize: 12),
                  textAlign: TextAlign.center,
                ),
              ),
              const SizedBox(height: 16),
              Expanded(
                child: ClipRRect(
                  borderRadius: BorderRadius.circular(16),
                  child: MobileScanner(
                    onDetect: (capture) {
                      final List<Barcode> barcodes = capture.barcodes;
                      for (final barcode in barcodes) {
                        final rawValue = barcode.rawValue;
                        if (rawValue != null && rawValue.isNotEmpty) {
                          final parsed = TestSimModel.fromQrString(rawValue);
                          if (parsed != null) {
                            Navigator.of(ctx).pop();
                            _handleScannedSim(parsed);
                            return;
                          }
                        }
                      }
                    },
                  ),
                ),
              ),
              const SizedBox(height: 16),
            ],
          ),
        );
      },
    );
  }

  void _handleScannedSim(TestSimEntity scanned) {
    showDialog(
      context: context,
      builder: (ctx) {
        return AlertDialog(
          title: const Row(
            children: [
              Icon(Icons.qr_code_scanner, color: Colors.teal),
              SizedBox(width: 8),
              Text('Scanned Test SIM'),
            ],
          ),
          content: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text('Card Name: ${scanned.cardName}', style: const TextStyle(fontWeight: FontWeight.bold)),
              const SizedBox(height: 6),
              Text('IMSI: ${scanned.imsi}', style: const TextStyle(fontFamily: 'monospace')),
              Text('Extension: ${scanned.extension}'),
              Text('Type: ${scanned.cardType}'),
              if (scanned.notes.isNotEmpty) ...[
                const SizedBox(height: 6),
                Text('Notes: ${scanned.notes}', style: const TextStyle(fontSize: 12, fontStyle: FontStyle.italic)),
              ],
            ],
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(ctx).pop(),
              child: const Text('Cancel'),
            ),
            OutlinedButton(
              onPressed: () {
                widget.notifier.addSimCard(scanned);
                Navigator.of(ctx).pop();
              },
              child: const Text('Save to My Cards'),
            ),
            FilledButton.icon(
              onPressed: () {
                Navigator.of(ctx).pop();
                widget.onStartFieldTest(scanned.imsi, scanned.extension);
              },
              icon: const Icon(Icons.play_arrow),
              label: const Text('Start Field Test'),
            ),
          ],
        );
      },
    );
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);

    return ListenableBuilder(
      listenable: widget.notifier,
      builder: (context, _) {
        final simCards = widget.notifier.simCards;

        return Scaffold(
          body: ListView(
            padding: const EdgeInsets.all(16),
            children: [
              // Privacy notice
              Card(
                color: Colors.amber.withValues(alpha: 0.12),
                child: const Padding(
                  padding: EdgeInsets.all(14),
                  child: Row(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Icon(Icons.privacy_tip_outlined, color: Colors.amber, size: 24),
                      SizedBox(width: 12),
                      Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text(
                              '🔒 SIM Privacy & Security Notice',
                              style: TextStyle(fontWeight: FontWeight.bold, fontSize: 13),
                            ),
                            SizedBox(height: 4),
                            Text(
                              'For academic laboratory safety, this manager strictly stores non-sensitive operational metadata (Card Label, IMSI, Extension, Notes). Sensitive cryptographic keys (Ki, OPc) are NEVER stored, requested, or transmitted.',
                              style: TextStyle(fontSize: 11, height: 1.35),
                            ),
                          ],
                        ),
                      ),
                    ],
                  ),
                ),
              ),
              const SizedBox(height: 16),

              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  Text(
                    'Registered Lab SIMs (${simCards.length})',
                    style: theme.textTheme.titleMedium?.copyWith(fontWeight: FontWeight.bold),
                  ),
                  Row(
                    children: [
                      OutlinedButton.icon(
                        onPressed: _openQrScanner,
                        icon: const Icon(Icons.qr_code_scanner, size: 18),
                        label: const Text('Scan QR', style: TextStyle(fontSize: 12)),
                        style: OutlinedButton.styleFrom(visualDensity: VisualDensity.compact),
                      ),
                      const SizedBox(width: 8),
                      FilledButton.icon(
                        onPressed: _showAddDialog,
                        icon: const Icon(Icons.add, size: 18),
                        label: const Text('Add SIM', style: TextStyle(fontSize: 12)),
                        style: FilledButton.styleFrom(visualDensity: VisualDensity.compact),
                      ),
                    ],
                  ),
                ],
              ),
              const SizedBox(height: 12),

              if (simCards.isEmpty)
                Card(
                  child: Padding(
                    padding: const EdgeInsets.all(32),
                    child: Center(
                      child: Column(
                        children: [
                          const Icon(Icons.sim_card, size: 48, color: Colors.grey),
                          const SizedBox(height: 12),
                          const Text('No test SIMs registered yet.'),
                          const SizedBox(height: 8),
                          TextButton.icon(
                            onPressed: _showAddDialog,
                            icon: const Icon(Icons.add),
                            label: const Text('Register First Test SIM'),
                          ),
                        ],
                      ),
                    ),
                  ),
                )
              else
                ListView.separated(
                  shrinkWrap: true,
                  physics: const NeverScrollableScrollPhysics(),
                  itemCount: simCards.length,
                  separatorBuilder: (_, _) => const SizedBox(height: 10),
                  itemBuilder: (context, index) {
                    final sim = simCards[index];
                    return SimCardItemWidget(
                      sim: sim,
                      onShowQr: () => _showQrDialog(sim),
                      onDelete: () => widget.notifier.deleteSimCard(sim.id),
                      onStartFieldTest: () => widget.onStartFieldTest(sim.imsi, sim.extension),
                    );
                  },
                ),
              const SizedBox(height: 24),
            ],
          ),
        );
      },
    );
  }
}
